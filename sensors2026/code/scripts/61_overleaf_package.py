"""
Stage 61 - zip the files Overleaf needs to compile the paper and the supplement.

numbers.tex, tables/*.tex and figures/*.pdf are generated by the analysis
scripts. Edit prose in Overleaf if convenient, but regenerate these files here
and upload them again rather than editing them by hand, or the paper and the
data will drift apart.

Usage: python scripts/61_overleaf_package.py
"""
from __future__ import annotations

import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
OUT = ROOT.parent / "ZsoP_MDPI_Sensors_quadruped_release" / "overleaf_quadruped_sensors.zip"


def main() -> None:
    files = [ROOT / "main.tex", ROOT / "numbers.tex", ROOT / "supplementary" / "supplementary.tex"]
    files += [p for p in (ROOT / "Definitions").rglob("*") if p.is_file()]
    files += sorted((ROOT / "figures").glob("*.pdf")) + sorted((ROOT / "tables").glob("*.tex"))
    OUT.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(OUT, "w", zipfile.ZIP_DEFLATED) as z:
        for f in files:
            z.write(f, f.relative_to(ROOT).as_posix())
    print(f"{len(files)} files -> {OUT} ({OUT.stat().st_size / 1e6:.1f} MB)")


if __name__ == "__main__":
    main()
