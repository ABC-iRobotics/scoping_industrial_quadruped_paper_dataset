"""Emit numbers.tex: every number the manuscript prints, as a LaTeX macro.

No number from the data is typed into main.tex. Prose reads e.g.
"\\Nscreened{} records were screened", and this script defines \\Nscreened
from the file that holds it. A value that does not exist yet is emitted as
\\numTODO{...}, which renders red and still compiles, so a missing number can
never ship looking like a real one.

Sources (each optional; a missing source leaves its macros as \\numTODO):
    work/prisma_counts.csv          39_prisma_flow.py
    work/validation/coding_time.csv 36_coding_time.py
    work/validation_accuracy.csv    37_validation_accuracy.py
    work/results_numbers.csv        50_results.py
    work/pipeline_numbers.csv       51_pipeline_accuracy.py
    work/review_time_numbers.csv    53_review_time.py

Usage:
    python scripts/40_emit_numbers.py        writes ../numbers.tex
"""
from __future__ import annotations

import statistics
from datetime import datetime
from pathlib import Path

import pandas as pd

from _common import WORK_DIR

OUT = WORK_DIR.parent.parent / "numbers.tex"


def fmt_int(n: int) -> str:
    """Thousands separated by a comma, braced for math-safe LaTeX."""
    return f"{n:,}".replace(",", "{,}")


def main() -> None:
    macros: dict[str, str] = {}
    provenance: list[str] = []

    p = WORK_DIR / "prisma_counts.csv"
    names = {
        "identified_total": "Nidentified", "identified_IEEE Xplore": "NidIEEE",
        "identified_Scopus": "NidScopus", "identified_Web of Science": "NidWoS",
        "duplicates_within_round": "Ndupwithin", "already_in_baseline": "Nbaselinematch",
        "screened": "Nscreened", "excluded_title_abstract": "NexclTA",
        "excluded_ta_pass1": "NexclTAone", "excluded_ta_pass2": "NexclTAtwo",
        "excluded_ta_model": "NexclTAmodel", "reinstated_on_recheck": "NreinstatedTA",
        "sought": "Nsought", "not_retrieved": "Nnotretrieved", "assessed": "Nassessed",
        "excluded_full_text": "NexclFT", "included_new": "Nincludednew",
        "previous_studies": "Nprevious", "included_total": "Nincluded",
    }
    if p.exists():
        s = pd.read_csv(p, index_col=0)["n"]
        for key, macro in names.items():
            macros[macro] = fmt_int(int(s[key])) if key in s else None
        provenance.append(f"{p.name}")
    else:
        for macro in names.values():
            macros[macro] = None

    p = WORK_DIR / "validation" / "coding_time.csv"
    if p.exists():
        t = pd.read_csv(p)
        t = t[t["total_min"] > 0]
        q = statistics.quantiles(t["total_min"], n=4)
        macros.update({
            "NcodingStudies": str(len(t)),
            "CodingTotalH": f"{t['total_min'].sum() / 60:.1f}",
            "CodingMedianMin": f"{statistics.median(t['total_min']):.1f}",
            "CodingIQRlo": f"{q[0]:.1f}", "CodingIQRhi": f"{q[2]:.1f}",
            "CodingMinMin": f"{t['total_min'].min():.1f}", "CodingMaxMin": f"{t['total_min'].max():.1f}",
        })
        provenance.append(p.name)
    else:
        for m in ("NcodingStudies", "CodingTotalH", "CodingMedianMin", "CodingIQRlo",
                  "CodingIQRhi", "CodingMinMin", "CodingMaxMin"):
            macros[m] = None

    # Results: every count 50_results.py derives from data/charting_v2.xlsx.
    # Macro names come from that script, so the two cannot drift apart.
    # Review-time macros are listed up front so a step not yet recorded prints
    # as a red \numTODO instead of breaking the build.
    for m in ("TimeCodebookMin", "TimeAdjMin", "TimeReadjMin", "TimeBaselineReviewMin", "TimeTitleScanMin",
              "ManualProjectedH", "PipelineHumanH", "TimeRatio", "TimeRatioWithVal"):
        macros.setdefault(m, None)
    for p in (WORK_DIR / "results_numbers.csv", WORK_DIR / "pipeline_numbers.csv",
              WORK_DIR / "review_time_numbers.csv"):
        if not p.exists():
            continue
        for macro, value in pd.read_csv(p, index_col=0, dtype=str)["value"].items():
            text = str(value)
            macros[macro] = fmt_int(int(text)) if text.isdigit() and not macro.startswith("Year") else text
        provenance.append(p.name)

    lines = [
        "% numbers.tex -- GENERATED by analysis/scripts/40_emit_numbers.py. Do not edit.",
        f"% generated {datetime.now().isoformat(timespec='seconds')} from: {', '.join(provenance) or 'nothing yet'}",
        "% A \\numTODO value is one the analysis has not produced yet.",
    ]
    for macro, value in macros.items():
        body = value if value is not None else f"\\numTODO{{{macro}}}"
        lines.append(f"\\newcommand{{\\{macro}}}{{{body}}}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    missing = [m for m, v in macros.items() if v is None]
    print(f"written {OUT}: {len(macros)} macros, {len(missing)} missing {missing}")


if __name__ == "__main__":
    main()
